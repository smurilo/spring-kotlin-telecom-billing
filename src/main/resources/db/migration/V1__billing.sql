CREATE TABLE subscribers (
    msisdn      VARCHAR(15) PRIMARY KEY,
    name        VARCHAR(120)  NOT NULL,
    plan        VARCHAR(20)   NOT NULL,
    monthly_fee NUMERIC(10, 2) NOT NULL
);

CREATE TABLE rated_usage (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    msisdn       VARCHAR(15)    NOT NULL REFERENCES subscribers (msisdn),
    usage_type   VARCHAR(10)    NOT NULL,
    started_at   TIMESTAMP      NOT NULL,
    units        BIGINT         NOT NULL,
    billed_units BIGINT         NOT NULL,
    amount       NUMERIC(12, 2) NOT NULL
);
CREATE INDEX idx_rated_usage_msisdn ON rated_usage (msisdn);

CREATE TABLE invoices (
    msisdn       VARCHAR(15)    NOT NULL,
    cycle        VARCHAR(20)    NOT NULL,
    voice_amount NUMERIC(12, 2) NOT NULL,
    sms_amount   NUMERIC(12, 2) NOT NULL,
    data_amount  NUMERIC(12, 2) NOT NULL,
    total        NUMERIC(12, 2) NOT NULL,
    PRIMARY KEY (msisdn, cycle)
);

